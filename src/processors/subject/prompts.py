def _format_signals(signals_dict: dict) -> str:
    """生成持仓信号描述字符串。"""
    lump = signals_dict.get("lump_sum_count", 0)
    dca = signals_dict.get("dca_count", 0)
    if lump > 0 and dca > 0:
        return (
            f"{lump} 只触发 LUMP-SUM({','.join(signals_dict.get('lump_sum_tickers', []))})、"
            f"{dca} 只触发 DCA({','.join(signals_dict.get('dca_tickers', []))})"
        )
    if lump > 0:
        return f"{lump} 只触发 LUMP-SUM({','.join(signals_dict.get('lump_sum_tickers', []))})"
    if dca > 0:
        return f"{dca} 只触发 DCA({','.join(signals_dict.get('dca_tickers', []))})"
    return "无信号"


def _format_mood(mood: dict) -> str:
    """生成情绪描述字符串。"""
    label = mood.get("label", "中性")
    parts = []
    if mood.get("cnn_fear_greed") is not None:
        parts.append(f"CNN={mood['cnn_fear_greed']:.0f}")
    if mood.get("vix") is not None:
        parts.append(f"VIX={mood['vix']:.1f}")
    if parts:
        return f"{label}({' '.join(parts)})"
    return label


def build_user_prompt(data: SubjectData, *, correction: str | None = None) -> str:
    """按 plan 的 user prompt 模板拼装。

    correction:第二次重试时的"上次输出哪里违反了格式"反馈,让模型纠正。
    """
    d = data.to_dict()
    signal_desc = _format_signals(d["signals"])
    mood_desc = _format_mood(d["mood"])
    holdings_news = d["holdings_news_top1"] or "无重大"
    macro_news = d["macro_news_top1"] or "无重大"

    # 截断邮件全文(保险二次截到 1500 字,避免 prompt 过长)
    full_text = data.email_full_text
    if len(full_text) > 1500:
        full_text = full_text[:1500] + "…"

    parts = [
        "今日数据:",
        f"- 节气:{d['solar_term']['current']}(节气短语建议:{d['solar_term']['phrase']})",
        f"- 市场情绪:{mood_desc}",
        f"- 持仓信号:{signal_desc}",
        f"- 持仓要闻:{holdings_news}",
        f"- 宏观要闻:{macro_news}",
        "",
        "邮件全文(供语境参考,不必直接引用):",
        "---",
        full_text,
        "---",
        "",
    ]

    if correction:
        parts.append(f"⚠️ 上次输出未通过验证,原因:{correction}")
        parts.append("请严格按【输出格式】重新生成 8 字主题,务必避开上述问题。")
    else:
        parts.append("请生成今日 8 字主题。")

    return "\n".join(parts)
